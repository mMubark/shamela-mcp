def register(mcp, context) -> None:

    @mcp.tool(
        name="shamela_guide",
        description=(
            "دليل عربي لاستعمال أدوات المكتبة الشاملة: منهج العمل، الأمثلة، أنماط البحث، "
            "معاني الحقول، الحدود، وحلّ المشكلات. مرّر section لطلب قسم بعينه: "
            "overview أو workflow أو examples أو modes أو fields أو limits أو troubleshooting."
        ),
    )
    @tool("shamela_guide")
    def shamela_guide(
        section: Annotated[
            str | None,
            Field(description="القسم المطلوب، أو اتركه فارغًا للدليل كاملًا."),
        ] = None,
    ) -> CallToolResult:
        if section:
            key = section.strip().lower()
            if key not in SECTIONS:
                available = "، ".join(SECTIONS)
                text = (
                    f"لا قسم باسم «{section}» في الدليل.\nالأقسام المتاحة: {available}."
                )
                return reply(text, {"sections": list(SECTIONS), "returned": []})
            return reply(SECTIONS[key], {"sections": list(SECTIONS), "returned": [key]})

        text = "\n\n".join(SECTIONS[key] for key in SECTIONS)
        return reply(text, {"sections": list(SECTIONS), "returned": list(SECTIONS)})
